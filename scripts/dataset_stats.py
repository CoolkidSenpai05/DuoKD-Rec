"""Statistics table of every processed dataset (M11): docs/dataset_stats.md (+ .json).

  python scripts/dataset_stats.py [--datasets beauty sports toys clothing]
Reads data.pkl / stats.json / stats_check.json and, when present, feature metadata (full catalog
and --limit runs) for the missing-modality rates.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.utils import get_logger, load_config, resolve  # noqa: E402

log = get_logger("dataset_stats")


def feat_info(cfg: dict) -> dict:
    base = resolve(cfg["features"]["feat_dir"])
    out = {}
    for d in [base] + sorted(base.parent.glob(base.name + "_limit*")):
        f = d / "feat_meta.json"
        if f.exists():
            m = json.loads(f.read_text())
            out["full" if d == base else d.name.split("_")[-1]] = m
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--datasets", nargs="+", default=["beauty", "sports", "toys", "clothing"])
    ap.add_argument("--out", default="docs/dataset_stats.md")
    args = ap.parse_args()
    rows = {}
    for ds in args.datasets:
        cfg = load_config("configs/base.yaml", [f"data.dataset={ds}"])
        d = resolve(cfg["data"]["processed_dir"])
        if not (d / "stats.json").exists():
            log.warning("%s: not processed, skipped", ds)
            continue
        st = json.loads((d / "stats.json").read_text())
        chk = json.loads((d / "stats_check.json").read_text()) if (d / "stats_check.json").exists() else {}
        rows[ds] = {"stats": st, "check": chk, "features": feat_info(cfg), "expected": cfg["data"]["expected"]}

    names = list(rows)
    def line(label, fn):
        return f"| {label} | " + " | ".join(fn(rows[n]) for n in names) + " |"
    st = lambda k, f="{:,}": (lambda r: f.format(r["stats"][k]))  # noqa: E731
    lines = ["| | " + " | ".join(names) + " |", "|---|" + "---|" * len(names),
             line("Users", st("n_users")), line("Items", st("n_items")),
             line("Interactions", st("n_interactions")),
             line("Expected U / I / inter.", lambda r: "{n_users:,} / {n_items:,} / {n_interactions:,}".format(**r["expected"])),
             line("Max rel. deviation", lambda r: "{:.2%}".format(max(v["rel_dev"] for v in r["check"]["fields"].values())) if r["check"] else "?"),
             line("Density", lambda r: "{:.3%}".format(r["stats"]["density"])),
             line("Seq. len mean / median", lambda r: "{:.2f} / {:g}".format(r["stats"]["seq_len_mean"], r["stats"]["seq_len_median"])),
             line("p90 / p95 / max", lambda r: "{:g} / {:g} / {}".format(r["stats"]["seq_len_p90"], r["stats"]["seq_len_p95"], r["stats"]["seq_len_max"])),
             line("Train samples (sliding window)", st("n_train_samples")),
             line("Valid / test target in history", lambda r: "{} / {}".format(r["stats"]["valid_target_in_history"], r["stats"]["test_target_in_history"])),
             line("Same-timestamp consecutive pairs", lambda r: "{:.1%}".format(r["check"]["time"]["zero_gap_frac"]) if r["check"] else "?")]

    def miss(r, key):
        parts = []
        for tag, m in r["features"].items():
            n = m["n_items"]
            parts.append(f"{tag}: {m[key]}/{n} ({m[key] / n:.1%})")
        return "; ".join(parts) or "not extracted"
    lines += [line("Missing text", lambda r: miss(r, "n_missing_text")),
              line("Missing image", lambda r: miss(r, "n_missing_img"))]
    out = resolve(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("# Dataset statistics (5-core, leave-one-out)\n\nGenerated by `scripts/dataset_stats.py`.\n\n"
                   + "\n".join(lines) + "\n")
    out.with_suffix(".json").write_text(json.dumps(rows, indent=2))
    log.info("wrote %s", out)


if __name__ == "__main__":
    main()
